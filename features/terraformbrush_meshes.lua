-----------------------------------------------------------------------------
--  Terrain meshes for the Terraformer's Feature Placer
-----------------------------------------------------------------------------
-- A terrain mesh is a feature whose model becomes part of the map: once it is
-- placed, the heightmap under it follows the model's upper surface and the
-- ground there turns near-indestructible (luarules/gadgets/cmd_terrain_mesh.lua).
-- The gadget reads the geometry from the s3o, so any model built in a 3D
-- package works with these tags:
--
--   customparams.terrainmesh        "1" opts the def in
--   customparams.terrainmesh_inset  elmos the mesh must cover past a heightmap
--                                   vertex before that vertex is raised
--                                   (default and floor: 8, one cell). The
--                                   terrain climbs to the top over the cell
--                                   after the last raised vertex, so the foot
--                                   of the climb sits inset - 8 elmos inside
--                                   the wall; keep the walls a couple of elmos
--                                   outside the stamped footprint and carry a
--                                   skirt below the origin.
--   customparams.terrainmesh_sink   elmos the stamped ground sits below the
--                                   mesh surface (default 0). Not needed for
--                                   the depth tie with the top face: cus_gl4
--                                   draws terrain meshes with a polygon offset.
--   blocking = false                units path over the raised ground, not
--                                   around a footprint; walls stop them by
--                                   slope like any cliff
--   upright = true                  tilt is the artist's, never the ground's
--
-- The concrete block model and its textures are generated by
-- c:/BAR-Github/tools/tf_mesh_block.py.

